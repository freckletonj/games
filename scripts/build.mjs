import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'..');
const read=async name=>readFile(resolve(root,name),'utf8');
const scripts=['src/platform/storage.js','src/platform/input.js','src/platform/levels.js','src/platform/art.js','src/platform/audio.js','src/games/animal-adventure/catalog.js','src/games/animal-adventure/game.js','src/main.js'];
const source=await read('index.html');
const css=await read('src/style.css');
const js=(await Promise.all(scripts.map(read))).map(code=>`<script>\n${code.replaceAll('</script>','<\\/script>')}\n</script>`).join('\n');
const map=(await readFile(resolve(root,'src/games/animal-adventure/levels/first-forest.png'))).toString('base64');
const html=source.replace('/* INLINE_CSS */',css).replace('<!-- INLINE_SCRIPTS -->',js).replace('__LEVEL_DATA__',`data:image/png;base64,${map}`);
await mkdir(resolve(root,'dist'),{recursive:true});
await writeFile(resolve(root,'dist/wonderwood.html'),html);
console.log(`Built dist/wonderwood.html (${(Buffer.byteLength(html)/1024).toFixed(1)} KiB, zero external requests)`);
